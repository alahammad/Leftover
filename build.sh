#!/bin/bash
# Builds Leftover.app (app + privileged helper), signs it, and optionally notarizes it.
#
#   ./build.sh                  universal release build into build/Leftover.app
#   SIGN_IDENTITY="..." ./build.sh       sign with a specific certificate
#   NOTARY_PROFILE=name ./build.sh       also notarize (xcrun notarytool store-credentials name)
#   BUNDLE_ID=com.you.leftover ./build.sh
set -euo pipefail
cd "$(dirname "$0")"

APP_NAME=Leftover
BUNDLE_ID="${BUNDLE_ID:-com.$(id -un | tr -cd 'a-zA-Z0-9').leftover}"
HELPER_ID="$BUNDLE_ID.helper"
VERSION=1.0.0
BUILD_NUMBER=$(date +%Y%m%d%H%M%S)
MIN_OS=13.0
ARCHS="${ARCHS:-arm64 x86_64}"

BUILD=build
APP="$BUILD/$APP_NAME.app"
GEN="$BUILD/gen"
OBJ="$BUILD/obj"

# --- Signing identity: prefer Developer ID, then Apple Development, else ad-hoc -------------
IDENTITY="${SIGN_IDENTITY:-}"
if [ -z "$IDENTITY" ]; then
    IDENTITIES=$(security find-identity -v -p codesigning)
    IDENTITY=$(echo "$IDENTITIES" | grep -o '"Developer ID Application: [^"]*"' | head -1 | tr -d '"' || true)
    [ -z "$IDENTITY" ] && IDENTITY=$(echo "$IDENTITIES" | grep -o '"Apple Development: [^"]*"' | head -1 | tr -d '"' || true)
fi
TEAM_ID=""
if [ -n "$IDENTITY" ]; then
    # The team ID is the certificate's OU (for "Apple Development" it differs from the ID in the name).
    TEAM_ID=$(security find-certificate -c "$IDENTITY" -p | openssl x509 -noout -subject \
        | grep -oE 'OU ?= ?[A-Z0-9]{10}' | head -1 | grep -oE '[A-Z0-9]{10}$')
    echo "Signing with: $IDENTITY (team $TEAM_ID)"
else
    echo "No signing certificate found: building ad-hoc signed (helper disabled)."
fi

# --- Generated build settings shared by app and helper --------------------------------------
rm -rf "$BUILD"
mkdir -p "$GEN" "$OBJ"
cat > "$GEN/BuildConfig.swift" <<EOF
// Generated by build.sh, do not edit.
enum BuildConfig {
    static let appBundleID = "$BUNDLE_ID"
    static let helperLabel = "$HELPER_ID"
    static let helperPlistName = "$HELPER_ID.plist"
    static let teamID = "$TEAM_ID"
    static let version = "$VERSION+$BUILD_NUMBER"
}
EOF

# --- Compile ---------------------------------------------------------------------------------
SWIFTFLAGS=(-swift-version 5 -O -whole-module-optimization)
for arch in $ARCHS; do
    echo "Compiling ($arch)…"
    swiftc "${SWIFTFLAGS[@]}" -parse-as-library -module-name Leftover \
        -target "$arch-apple-macos$MIN_OS" \
        Sources/App/*.swift Sources/Shared/*.swift "$GEN/BuildConfig.swift" \
        -o "$OBJ/Leftover-$arch"
    swiftc "${SWIFTFLAGS[@]}" -module-name LeftoverHelper \
        -target "$arch-apple-macos$MIN_OS" \
        Sources/Helper/*.swift Sources/Shared/*.swift "$GEN/BuildConfig.swift" \
        -o "$OBJ/LeftoverHelper-$arch"
done

# --- Assemble the bundle -----------------------------------------------------------------------
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Library/LaunchDaemons" "$APP/Contents/Resources"
lipo -create "$OBJ"/Leftover-* -output "$APP/Contents/MacOS/Leftover"
lipo -create "$OBJ"/LeftoverHelper-* -output "$APP/Contents/MacOS/LeftoverHelper"

substitute() {
    sed -e "s/__BUNDLE_ID__/$BUNDLE_ID/g" -e "s/__HELPER_ID__/$HELPER_ID/g" \
        -e "s/__VERSION__/$VERSION/g" -e "s/__BUILD__/$BUILD_NUMBER/g" -e "s/__MIN_OS__/$MIN_OS/g" "$1"
}
substitute Resources/Info.plist > "$APP/Contents/Info.plist"
substitute Resources/helper-launchd.plist > "$APP/Contents/Library/LaunchDaemons/$HELPER_ID.plist"
printf 'APPL????' > "$APP/Contents/PkgInfo"

# --- Sign: helper first, then the app around it --------------------------------------------------
if [ -n "$IDENTITY" ]; then
    SIGN=(--force --options runtime -s "$IDENTITY")
    [[ "$IDENTITY" == "Developer ID Application:"* ]] && SIGN+=(--timestamp)
else
    SIGN=(--force -s -)
fi
codesign "${SIGN[@]}" -i "$HELPER_ID" "$APP/Contents/MacOS/LeftoverHelper"
codesign "${SIGN[@]}" -i "$BUNDLE_ID" "$APP"
codesign --verify --strict --deep "$APP"

# --- Optional notarization ------------------------------------------------------------------------
if [ -n "${NOTARY_PROFILE:-}" ]; then
    echo "Notarizing…"
    ditto -c -k --keepParent "$APP" "$BUILD/$APP_NAME.zip"
    xcrun notarytool submit "$BUILD/$APP_NAME.zip" --keychain-profile "$NOTARY_PROFILE" --wait
    xcrun stapler staple "$APP"
fi

echo "Built $APP ($VERSION, build $BUILD_NUMBER, bundle id $BUNDLE_ID)"
